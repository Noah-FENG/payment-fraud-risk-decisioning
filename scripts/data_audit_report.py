"""Stage 1 data audit: regenerate the descriptive audit report from prepared data.

Reads ``data/processed/transactions.parquet`` and ``data/processed/data_audit.json``
and writes ``reports/generated/data_audit_report.md``. Every number in the report is
computed at run time by DuckDB against the prepared table; nothing is hand-filled.

Usage:
    uv run python scripts/data_audit_report.py
"""

from __future__ import annotations

import json
from pathlib import Path

import duckdb

from fraud.io import read_sql

ROOT = Path(__file__).resolve().parents[1]
PARQUET = ROOT / "data" / "processed" / "transactions.parquet"
AUDIT_JSON = ROOT / "data" / "processed" / "data_audit.json"
OUTPUT = ROOT / "reports" / "generated" / "data_audit_report.md"

AMOUNT_LABELS = ["[0,25)", "[25,50)", "[50,100)", "[100,250)", "[250,500)", "[500,1000)", "[1000,inf)"]


def sql_literal(value) -> str:
    return "'" + str(value).replace("'", "''") + "'"


def md_table(headers: list[str], rows: list[list]) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    for row in rows:
        lines.append("| " + " | ".join(str(cell) for cell in row) + " |")
    return "\n".join(lines)


def pct(part, whole) -> str:
    return f"{100.0 * part / whole:.2f}%" if whole else "n/a"


def main() -> None:
    audit = json.loads(AUDIT_JSON.read_text(encoding="utf-8"))
    con = duckdb.connect()
    con.execute(f"CREATE VIEW t AS SELECT * FROM read_parquet({sql_literal(PARQUET)})")

    # --- overview -----------------------------------------------------------
    row = con.execute(read_sql("audit_overview.sql")).fetchone()
    n, n_fraud, t_min, t_max, amt_total, fraud_amt_total, n_id_missing = row
    span_days = (t_max - t_min) / 86400.0

    # --- amount buckets -------------------------------------------------------
    amount_rows = con.execute(read_sql("audit_amount_buckets.sql")).fetchall()

    # --- generic segment helper ----------------------------------------------
    def segments(column: str, limit: int | None = None):
        return con.execute(
            read_sql("audit_segments.sql", column=column, limit_clause=f"LIMIT {limit}" if limit else "")
        ).fetchall()

    product_rows = segments("ProductCD")
    devicetype_rows = segments("DeviceType")
    deviceinfo_rows = segments("DeviceInfo", limit=10)
    identity_rows = con.execute(read_sql("audit_identity.sql")).fetchall()
    email_rows = segments("P_emaildomain", limit=10)
    card4_rows = segments("card4")

    # --- missingness ----------------------------------------------------------
    tx_cols = audit["tables"]["transaction"]["columns"]
    id_cols = audit["tables"]["identity"]["columns"]
    tx_n = audit["tables"]["transaction"]["rows"]
    id_n = audit["tables"]["identity"]["rows"]

    def miss_band(cols, rows):
        bands = {"0%": 0, "(0%,10%]": 0, "(10%,50%]": 0, "(50%,90%]": 0, ">90%": 0}
        for c in cols:
            f = c["missing_fraction"]
            if f == 0:
                bands["0%"] += 1
            elif f <= 0.10:
                bands["(0%,10%]"] += 1
            elif f <= 0.50:
                bands["(10%,50%]"] += 1
            elif f <= 0.90:
                bands["(50%,90%]"] += 1
            else:
                bands[">90%"] += 1
        return bands, rows

    tx_bands, _ = miss_band(tx_cols, tx_n)
    id_bands, _ = miss_band(id_cols, id_n)
    top_missing_tx = sorted(tx_cols, key=lambda c: -c["missing_fraction"])[:10]
    top_missing_id = sorted(id_cols, key=lambda c: -c["missing_fraction"])[:10]

    # --- time profile ---------------------------------------------------------
    week_rows = con.execute(read_sql("audit_weekly.sql")).fetchall()

    # --- write report -----------------------------------------------------------
    out = []
    out.append("# Data audit report (stage 1)\n")
    out.append(
        "This report is generated by `scripts/data_audit_report.py` from `data/processed/transactions.parquet` and "
        "`data_audit.json`, recomputed with DuckDB at run time; no number is typed by hand. "
        "The source is the official IEEE-CIS Fraud Detection training files; amounts keep the original, unstated unit, "
        "and fraud-labelled amount is not realised loss.\n"
    )

    out.append("## Overview\n")
    out.append(md_table(
        ["Metric", "Value"],
        [
            ["Transactions", f"{n:,}"],
            ["Fraud transactions", f"{n_fraud:,}"],
            ["Fraud rate", pct(n_fraud, n)],
            ["TransactionDT min / max (seconds offset)", f"{t_min:,} / {t_max:,}"],
            ["Time span (days)", f"{span_days:.1f}"],
            ["Transactions without identity record", f"{n_id_missing:,} ({pct(n_id_missing, n)})"],
            ["Total transaction amount", f"{amt_total:,.2f}"],
            ["Fraud-labelled amount (share)", f"{fraud_amt_total:,.2f} ({pct(fraud_amt_total, amt_total)})"],
        ],
    ))
    out.append("")

    out.append("## Amount buckets\n")
    out.append(md_table(
        ["Amount range", "Transactions", "Share", "Fraud rate", "Share of fraud amount*"],
        [
            [
                AMOUNT_LABELS[int(b)] if b is not None else "n/a",
                f"{cnt:,}", pct(cnt, n), pct(nf, cnt), pct(famt, fraud_amt_total),
            ]
            for b, cnt, nf, amt, famt in amount_rows
        ],
    ))
    out.append("\n*Share of all fraud-labelled amount that falls in this bucket.\n")

    def segment_section(title, rows):
        out.append(f"## {title}\n")
        out.append(md_table(
            ["Group", "Transactions", "Share", "Fraud rate", "Share of fraud amount*"],
            [[seg, f"{cnt:,}", pct(cnt, n), pct(nf, cnt), pct(famt, fraud_amt_total)]
             for seg, cnt, nf, famt in rows],
        ))
        out.append("")

    segment_section("Product (ProductCD)", product_rows)
    segment_section("Device type (DeviceType, identity-table field)", devicetype_rows)
    segment_section("Device info (DeviceInfo, top 10)", deviceinfo_rows)
    segment_section("Identity record present or absent", identity_rows)
    segment_section("Purchaser e-mail domain (P_emaildomain, top 10)", email_rows)
    segment_section("Card brand (card4)", card4_rows)

    out.append("## Missing-value overview\n")
    out.append("Columns bucketed by missing share (transaction table: %d columns; identity table: %d columns, identity coverage %.2f%% of transactions):\n" % (
        len(tx_cols), len(id_cols), 100.0 * (1 - n_id_missing / n)))
    out.append(md_table(
        ["Missing-share band", "Transaction-table columns", "Identity-table columns"],
        [[band, tx_bands[band], id_bands[band]] for band in tx_bands],
    ))
    out.append("\nTop 10 columns by missing share in the transaction table:\n")
    out.append(md_table(["Column", "Missing share"], [[c["name"], pct(c["missing_count"], tx_n)] for c in top_missing_tx]))
    out.append(f"\nTop 10 columns by missing share in the identity table (out of {id_n:,} rows):\n")
    out.append(md_table(["Column", "Missing share"], [[c["name"], pct(c["missing_count"], id_n)] for c in top_missing_id]))
    out.append("")

    out.append("## Change over relative time (weekly)\n")
    out.append(md_table(
        ["Relative week", "Transactions", "Fraud rate", "Average amount", "Share without identity record"],
        [[int(wk), f"{cnt:,}", pct(nf, cnt), f"{avg:.2f}", f"{100.0*im:.1f}%"]
         for wk, cnt, nf, avg, im in week_rows],
    ))
    out.append("")
    out.append(
        "\n> Note: these offline descriptive statistics describe only this historical sample and must not be extrapolated to a production fraud rate; "
        "a missing identity record reflects how the data was collected and does not make a transaction suspicious.\n"
    )

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
