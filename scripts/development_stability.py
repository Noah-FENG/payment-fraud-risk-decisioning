"""Stage 2 follow-up: group performance and weekly stability on the policy segment.

Reads ``artifacts/main/policy_predictions.parquet`` plus the prepared table and writes
``reports/generated/development_stability.md``. All numbers are recomputed at run time
from those run artefacts; nothing is hand-filled. The final test segment is untouched.

Usage:
    uv run python scripts/development_stability.py
"""

from __future__ import annotations

import json
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.metrics import average_precision_score, roc_auc_score

ROOT = Path(__file__).resolve().parents[1]
RUN = ROOT / "artifacts" / "main"
OUTPUT = ROOT / "reports" / "generated" / "development_stability.md"

AMOUNT_EDGES = [0, 25, 50, 100, 250, 500, 1000, np.inf]
AMOUNT_LABELS = ["[0,25)", "[25,50)", "[50,100)", "[100,250)", "[250,500)", "[500,1000)", "[1000,inf)"]


def pct(part, whole) -> str:
    return f"{100.0 * part / whole:.2f}%" if whole else "n/a"


def md_table(headers, rows) -> str:
    lines = ["| " + " | ".join(headers) + " |", "| " + " | ".join("---" for _ in headers) + " |"]
    lines += ["| " + " | ".join(map(str, r)) + " |" for r in rows]
    return "\n".join(lines)


def main() -> None:
    manifest = json.loads((RUN / "development.json").read_text(encoding="utf-8"))
    chosen = manifest["chosen_model"]
    pred = pd.read_parquet(RUN / "policy_predictions.parquet")

    prepared = pd.read_parquet(
        ROOT / "data" / "processed" / "transactions.parquet",
        columns=["TransactionID", "ProductCD", "DeviceType", "identity_missing"],
    )
    frame = pred.merge(prepared, on="TransactionID", how="left", validate="one_to_one")
    frame["relative_week"] = np.floor(frame.TransactionDT / (86400 * 7)).astype(int)
    frame["amount_bucket"] = pd.cut(frame.TransactionAmt, AMOUNT_EDGES, right=False,
                                    labels=AMOUNT_LABELS).astype(str)
    frame["identity"] = np.where(frame.identity_missing, "no identity record", "has identity record")
    frame["DeviceType"] = frame.DeviceType.astype("string").fillna("Missing")

    score = frame[chosen].to_numpy()
    # Recreate the run's daily top-rate selection (same rule as pipeline._metrics_rows).
    day = np.floor(frame.TransactionDT.to_numpy() / manifest["config"]["batch_seconds"]).astype(int)
    rate = manifest["config"]["primary_review_rate"]
    selected = np.zeros(len(frame), dtype=bool)
    for d in np.unique(day):
        mask = day == d
        k = max(1, int(np.floor(mask.sum() * rate)))
        top = np.argsort(-score[mask])[:k]
        selected[np.flatnonzero(mask)[top]] = True
    frame["selected"] = selected

    def group_rows(dim):
        rows = []
        for seg, g in frame.groupby(dim, observed=True):
            if g.isFraud.nunique() < 2:
                ap, auc = "n/a", "n/a"
            else:
                ap = f"{average_precision_score(g.isFraud, g[chosen]):.4f}"
                auc = f"{roc_auc_score(g.isFraud, g[chosen]):.4f}"
            tp = int((g.selected & (g.isFraud == 1)).sum())
            sel = int(g.selected.sum())
            rows.append([str(seg), f"{len(g):,}", pct(int(g.isFraud.sum()), len(g)),
                         ap, auc, f"{sel:,}", pct(tp, int(g.isFraud.sum())),
                         pct(tp, sel) if sel else "n/a"])
        return rows

    out = ["# Stage 2 addendum: policy-block group performance and time stability\n",
           f"Regenerated by `scripts/development_stability.py` from `policy_predictions.parquet`. "
           f"The model is the `{chosen}` selected by develop (sigmoid-calibrated score); review selection is the daily top "
           f"{rate:.1%} (same as develop). Only the policy block is used; the final test block is untouched.\n"]
    headers = ["Group", "Transactions", "Fraud rate", "AP", "ROC-AUC", "Reviewed", "Within-group recall", "Review precision"]
    for dim, title in [("ProductCD", "product"), ("amount_bucket", "amount bucket"), ("identity", "identity record"),
                       ("DeviceType", "device type"), ("relative_week", "relative week")]:
        out.append(f"## By {title}\n")
        out.append(md_table(headers, group_rows(dim)))
        out.append("")

    weekly = frame.groupby("relative_week", observed=True).agg(n=("isFraud", "size"))
    ap_by_week = [average_precision_score(g.isFraud, g[chosen])
                  for _, g in frame.groupby("relative_week", observed=True) if g.isFraud.nunique() == 2]
    out.append("## Stability summary\n")
    out.append(f"- Weeks: {len(weekly)}; weekly AP min / median / max: "
               f"{min(ap_by_week):.4f} / {np.median(ap_by_week):.4f} / {max(ap_by_week):.4f}.")
    out.append("- Descriptive evidence only: group differences reflect this historical sample and the score ranking, not the causal risk of any group.\n")

    OUTPUT.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {OUTPUT} ({OUTPUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
